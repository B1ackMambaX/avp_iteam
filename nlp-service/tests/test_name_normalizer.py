# Допустимо вернуть None (запасной путь), но не неверную строку
SAFE = [
    ("Сидоров И.П.", "Сидоров И.П."),
    ("Шевченко Ирина Павловна", "Шевченко Ирина Павловна"),
    ("Ковалевич Анна Ивановна", "Ковалевич Анна Ивановна"),
    ("Петрова-Водкина Анна Ивановна", "Петрова-Водкина Анна Ивановна"),
]

@pytest.mark.parametrize("src, expected", SAFE)
def test_never_wrong(src, expected):
    assert norm(src) in (expected, None)

